/// Terse const constructor for a [`ClassifierRule`].
#[allow(clippy::too_many_arguments)]
const fn r(
    id: &'static str,
    format: &'static str,
    category: CorruptionCategory,
    default_severity: Severity,
    description: &'static str,
    affected_field: &'static str,
    evidence_type: EvidenceType,
    confidence_deterministic: bool,
) -> ClassifierRule {
    ClassifierRule {
        id,
        format,
        category,
        default_severity,
        description,
        affected_field,
        evidence_type,
        confidence_deterministic,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn lookup_known_rule() {
        let rule = rule("ZIP_EOCD_001").unwrap();
        assert_eq!(rule.category, CorruptionCategory::StructuralCorruption);
        assert_eq!(rule.default_severity, Severity::Catastrophic);
    }

    #[test]
    fn unknown_rule_is_none() {
        assert!(rule("NOPE_999").is_none());
    }

    #[test]
    fn all_rule_ids_unique() {
        let mut ids: Vec<&str> = RULES.iter().map(|r| r.id).collect();
        ids.sort_unstable();
        let len = ids.len();
        ids.dedup();
        assert_eq!(ids.len(), len, "duplicate rule id in registry");
    }

    #[test]
    fn matrix_rule_ids_present() {
        for id in [
            "ZIP_CRC_001",
            "TAR_UST_001",
            "ISO_PVD_001",
            "GZ_MAGIC_001",
            "PDF_HDR_001",
            "SQ_MAGIC_001",
        ] {
            assert!(rule(id).is_some(), "missing {id}");
        }
    }

    #[test]
    fn security_rules_present_and_categorized() {
        for id in [
            "SEC_BOMB_RATIO_001",
            "SEC_BOMB_OUTPUT_001",
            "SEC_BOMB_OVERLAP_001",
            "SEC_CYCLE_001",
            "SEC_DEPTH_001",
            "SEC_ENTRIES_001",
            "SEC_TRAVERSAL_001",
            "SEC_SYMLINK_001",
            "SEC_PARSER_TIMEOUT_001",
        ] {
            let r = rule(id).unwrap_or_else(|| panic!("missing {id}"));
            assert_eq!(
                r.category,
                CorruptionCategory::SecurityThreat,
                "{id} must be a SecurityThreat"
            );
        }
    }
}
