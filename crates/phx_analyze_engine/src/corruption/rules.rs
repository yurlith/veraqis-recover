//! Classifier rule registry (Phase 2, Step 2.3).
//!
//! Every classifier rule is a static, compile-time entry. Rules are referenced
//! by `rule_id` string from [`Evidence`](crate::model::Evidence) and from the
//! corpus `metadata.json`. `format` is a `&'static str` (not `ArchiveFormat`)
//! so the registry can cover all 12 corpus formats, not just the four the
//! engine parses today.

use crate::model::{CorruptionCategory, EvidenceType, Severity};

/// A single classifier rule.
#[derive(Debug, Clone, Copy)]
pub struct ClassifierRule {
    pub id: &'static str,
    pub format: &'static str,
    pub category: CorruptionCategory,
    pub default_severity: Severity,
    pub description: &'static str,
    pub affected_field: &'static str,
    pub evidence_type: EvidenceType,
    /// `true` ⇒ confidence is always 1.0 (signature/offset checks).
    pub confidence_deterministic: bool,
}

/// Look up a rule by id.
pub fn rule(id: &str) -> Option<&'static ClassifierRule> {
    RULES.iter().find(|r| r.id == id)
}

